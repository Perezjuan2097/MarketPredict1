    const currencySymbols = { EUR: "€", USD: "$", GBP: "£", JPY: "¥", CHF: "CHF ", CAD: "C$", AUD: "A$", HKD: "HK$", SEK: "kr ", NOK: "kr ", DKK: "kr ", PLN: "zł " };

    function currencySymbol(code) {
        return currencySymbols[String(code || "USD").toUpperCase()] || `${code || "USD"} `;
    }

    function formatMoney(value, currency = "USD") {
        const n = Number(value);
        if (!Number.isFinite(n)) return "—";
        const code = String(currency || "USD").toUpperCase();
        const locale = language === "es" ? "es-CO" : "en-US";
        return `${currencySymbol(code)}${n.toLocaleString(locale, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
    }

    function formatNumber(value) {
        const n = Number(value);
        return Number.isFinite(n) ? n.toLocaleString(language === "es" ? "es-CO" : "en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 }) : "—";
    }

    function formatPercent(value) {
        const n = Number(value);
        return Number.isFinite(n) ? `${n >= 0 ? "+" : ""}${n.toFixed(2).replace(".", language === "es" ? "," : ".")}%` : "—";
    }

    function formatDateTime(value) {
        if (!value) return "—";
        const date = new Date(value);
        if (Number.isNaN(date.getTime())) return "—";
        return new Intl.DateTimeFormat(language === "es" ? "es-CO" : "en-US", {
            day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit"
        }).format(date);
    }

    function setStatus(message) {
        if (exists("#status")) $("#status").textContent = message;
    }

    function escapeHTML(value) {
        return String(value ?? "").replace(/[&<>'"]/g, (char) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "'": "&#39;", '"': "&quot;" }[char]));
    }

    function applyLanguage() {
        const dict = translations[language];
        $$('[data-i18n]').forEach((element) => {
            const key = element.dataset.i18n;
            if (dict[key]) element.textContent = dict[key];
        });
        $$('[data-i18n-placeholder]').forEach((element) => {
            const key = element.dataset.i18nPlaceholder;
            if (dict[key]) element.placeholder = dict[key];
        });
        if (exists("#languageToggle")) $("#languageToggle").innerHTML = `${language.toUpperCase()} <span>⌄</span>`;
        if (marketData) renderMarketHeader(marketData);
        if (marketData) renderChart(marketData.data || []);
    }

    function restoreTheme() {
        if (localStorage.getItem("marketpredict-theme") === "dark") document.body.classList.add("dark-mode");
    }

    function toggleTheme() {
        document.body.classList.toggle("dark-mode");
        localStorage.setItem("marketpredict-theme", document.body.classList.contains("dark-mode") ? "dark" : "light");
        if (marketData) renderChart(marketData.data || []);
        if (seasonalInstance) loadSeasonal(activeTicker);
    }

    function renderMarketHeader(data) {
        const symbol = data.symbol || "—";
        if (exists("#assetBadge")) $("#assetBadge").textContent = symbol.replace(/^\^/, "").slice(0, 3);
        if (exists("#assetTitle")) $("#assetTitle").textContent = data.name || symbol;
        if (exists("#assetTicker")) $("#assetTicker").textContent = symbol;
        if (exists("#provider")) $("#provider").textContent = `${data.provider || "Yahoo Finance"}${data.exchange ? ` · ${data.exchange}` : ""}`;
        if (exists("#priceUnit")) $("#priceUnit").textContent = data.currency || "USD";
        if (exists("#currentPrice")) $("#currentPrice").textContent = formatMoney(data.current_price, data.currency);
        if (exists("#changeAbsolute")) $("#changeAbsolute").textContent = `${Number(data.change_absolute) >= 0 ? "+" : ""}${formatMoney(data.change_absolute, data.currency)}`;
        if (exists("#changePercent")) $("#changePercent").textContent = formatPercent(data.change_percent);
        if (exists("#priceChange")) $("#priceChange").className = `price-change ${Number(data.change_percent) >= 0 ? "positive" : "negative"}`;
        if (exists("#marketStatus")) $("#marketStatus").textContent = `${language === "es" ? "Último dato" : "Latest data"}: ${formatDateTime(data.last_timestamp)}`;
        if (exists("#intervalLabel")) $("#intervalLabel").textContent = data.interval === "1d" ? (language === "es" ? "Diario" : "Daily") : data.interval;
        if (exists("#intervalCode")) $("#intervalCode").textContent = data.interval === "1d" ? "D" : data.interval;
    }

    function renderCards(indicators = []) {
        if (!exists("#cards")) return;
        $("#cards").innerHTML = indicators.map((item) => `<article class="card"><small>${escapeHTML(item.nombre || "Indicador")}</small><strong>${formatMoney(item.valor, marketData?.currency)}</strong><small>${escapeHTML(item.descripcion || "")}</small></article>`).join("");
    }

    function renderPredictions(predictions = []) {
        if (!exists("#predictions")) return;
        if (!predictions.length) {
            $("#predictions").innerHTML = `<div class="empty-state">No hay predicciones disponibles.</div>`;
            return;
        }
        const range = (p) => (p.intervalo_bajo && p.intervalo_alto) ? `${formatMoney(p.intervalo_bajo, marketData?.currency)} – ${formatMoney(p.intervalo_alto, marketData?.currency)}` : "—";
        const notes = [...new Set(predictions.map((p) => p.nota).filter(Boolean))];
        $("#predictions").innerHTML = `<table class="table"><thead><tr><th>Modelo</th><th>Fecha objetivo</th><th>Estimación</th><th>Rango orientativo</th></tr></thead><tbody>${predictions.map((p) => `<tr><td>${escapeHTML(p.modelo)} <small>${escapeHTML(p.version || "")}</small></td><td>${escapeHTML(p.fecha_objetivo)}<br><small>${escapeHTML(p.horizonte)}</small></td><td><strong>${formatMoney(p.valor_estimado, marketData?.currency)}</strong></td><td>${range(p)}</td></tr>`).join("")}</tbody></table><p class="note">Los rangos individuales usan el error histórico de cada modelo. El rango del consenso resume los errores de sus integrantes y su cobertura es desconocida.</p>${notes.map((n) => `<p class="note">${escapeHTML(n)}</p>`).join("")}`;
    }

    function renderAlert(alert) {
        if (!exists("#alert")) return;
        if (!alert) {
            $("#alert").innerHTML = `<div class="empty-state">Sin señal.</div>`;
            return;
        }
        const level = { ALTA: "ALTA", MEDIA: "MEDIA", BAJA: "BAJA" }[alert.nivel] || "NEUTRA";
        $("#alert").innerHTML = `<div class="alert ${level}"><span class="pill">${escapeHTML(alert.nivel || "BAJA")}</span><p>${escapeHTML(alert.fundamento || "Sin fundamento disponible.")}</p></div>`;
    }

    async function analyzeAsset(query) {
        setStatus("Consultando y procesando datos...");
        const response = await fetch("/api/analyze", { method: "POST", headers: { "Content-Type": "application/json", ...headers }, body: JSON.stringify({ symbol: query }) });
        const data = await response.json();
        if (!response.ok) throw new Error(data.error || "No fue posible analizar el activo.");
        current = data;
        activeTicker = data.symbol;
        renderCards(data.indicators);
        renderPredictions(data.predictions);
        renderAlert(data.alert);
        if (exists("#trend")) $("#trend").textContent = `Tendencia: ${data.tendency || "—"}`;
        if (exists("#modelVersion")) $("#modelVersion").textContent = data.model_version || "—";
        await loadMarketData(activeTicker, selectedPeriod, false);
        renderCards(data.indicators);
        renderPredictions(data.predictions);
        await loadHistory();
        setStatus(data.data_source === "demo" ? "Análisis completado con DATOS DEMO sintéticos: no son datos de mercado." : "Análisis completado.");
    }

    async function loadMarketData(query, period = selectedPeriod, showStatus = true) {
        if (showStatus) setStatus(`Cargando ${period}...`);
        const response = await fetch(`/api/market-data/${encodeURIComponent(query)}?period=${encodeURIComponent(period)}`);
        const data = await response.json();
        if (!response.ok) throw new Error(data.error || "No fue posible obtener datos de mercado.");
        marketData = data;
        activeTicker = data.symbol;
        selectedPeriod = period;
        renderMarketHeader(data);
        renderChart(data.data || []);
        renderPerformance(data);
        if (showStatus) setStatus("Datos de mercado actualizados.");
    }

    function renderPerformance(data) {
        if (exists("#periodPerformance")) {
            const value = Number(data.change_percent);
            $("#periodPerformance").textContent = `${value >= 0 ? "▲" : "▼"} Rendimiento del período: ${formatPercent(value)}`;
            $("#periodPerformance").style.color = value >= 0 ? "var(--green)" : "var(--red)";
        }
        if (exists("#previousClose")) $("#previousClose").innerHTML = `Cierre anterior <strong>${formatMoney(data.previous_close, data.currency)}</strong>`;
    }

    function renderChart(data) {
        if (!exists("#chart") || typeof Chart === "undefined") return;
        const values = data.map((item) => Number(item.cierre));
        if (!values.length) return;
        if (chartInstance) chartInstance.destroy();
        const ctx = $("#chart").getContext("2d");
        const dark = document.body.classList.contains("dark-mode");
        const lineColor = dark ? "#4ade80" : "#0a9f6e";
        const gridColor = dark ? "rgba(255,255,255,.08)" : "rgba(16,24,40,.08)";
        const textColor = dark ? "#b7c1ce" : "#667085";
        const gradient = ctx.createLinearGradient(0, 0, 0, 330);
        gradient.addColorStop(0, dark ? "rgba(74,222,128,.24)" : "rgba(10,159,110,.20)");
        gradient.addColorStop(1, "rgba(10,159,110,0)");
        const labels = data.map((item) => item.fecha);

        chartInstance = new Chart(ctx, {
            type: "line",
            data: { labels, datasets: [{ label: marketData?.symbol || "Activo", data: values, borderColor: lineColor, backgroundColor: gradient, fill: true, borderWidth: 2, pointRadius: 0, pointHoverRadius: 4, tension: .22 }] },
            options: {
                responsive: true, maintainAspectRatio: false,
                interaction: { mode: "index", intersect: false },
                plugins: {
                    legend: { display: false },
                    tooltip: {
                        callbacks: {
                            title: (items) => formatDateTime(items[0]?.label),
                            label: (item) => `${formatMoney(item.parsed.y, marketData?.currency)} · ${formatPercent(data[item.dataIndex]?.variacion)}`
                        }
                    }
                },
                scales: {
                    x: { ticks: { color: textColor, maxTicksLimit: 8, callback: (value) => formatShortDate(labels[value]) }, grid: { color: gridColor } },
                    y: { ticks: { color: textColor, callback: (value) => formatMoney(value, marketData?.currency) }, grid: { color: gridColor } }
                }
            }
        });
    }

    function formatShortDate(value) {
        const date = new Date(value);
        if (Number.isNaN(date.getTime())) return value;
        return new Intl.DateTimeFormat(language === "es" ? "es-CO" : "en-US", { day: "2-digit", month: "short" }).format(date);
    }

    async function loadHistory() {
        if (!exists("#history")) return;
        const principal = currentUser;
        if (!currentUser) {
            $("#history").textContent = "Inicia sesión para consultar tu historial.";
            return;
        }
        try {
            const response = await fetch("/api/history");
            if (!response.ok) throw new Error();
            const data = await response.json();
            if (currentUser !== principal) return;
            $("#history").innerHTML = data.length ? `<table class="table"><thead><tr><th>Activo</th><th>Fecha</th><th>Predicción</th><th>Modelo</th></tr></thead><tbody>${data.slice(0, 8).map((r) => `<tr><td><strong>${escapeHTML(r.symbol)}</strong></td><td>${escapeHTML(r.fecha)}</td><td>${formatMoney(r.prediccion, marketData?.currency)}</td><td>${escapeHTML(r.modelo)}</td></tr>`).join("")}</tbody></table>` : `<div class="empty-state">No hay predicciones guardadas todavía.</div>`;
        } catch {
            $("#history").textContent = "No fue posible cargar el historial.";
        }
    }

    function safeNewsUrl(value) {
        try {
            const url = new URL(value);
            return url.protocol === "https:" || url.protocol === "http:";
        } catch {
            return false;
        }
    }

    async function loadNews(ticker) {
        const box = $("#newsContent");
        box.innerHTML = `<div class="loading">Cargando noticias...</div>`;
        try {
            const response = await fetch(`/api/news/${encodeURIComponent(ticker)}`);
            const data = await response.json();
            if (!response.ok) throw new Error(data.error);
            const p = data.pulse;
            const head = p && p.headlines ? `<div class="alert ${p.score >= 0.15 ? "BAJA" : p.score <= -0.15 ? "ALTA" : "NEUTRA"}" style="margin-bottom:12px"><span class="pill">PULSO DE NOTICIAS: ${escapeHTML(p.label.toUpperCase())}</span><p>${p.counts.positivo} titulares positivos, ${p.counts.neutral} neutrales y ${p.counts.negativo} negativos (fuente: ${escapeHTML(data.provider || "")}). ${escapeHTML(p.note)}</p></div>` : "";
            const tones = Object.fromEntries((p?.items || []).map((i) => [i.title, i.tone]));
            box.innerHTML = head + (data.news.length ? data.news.map((item) => `<article class="news-item"><div><span class="news-source">${escapeHTML(item.source)}${tones[item.title] && tones[item.title] !== "neutral" ? ` · <span class="${tones[item.title] === "positivo" ? "positive-text" : "negative-text"}">${tones[item.title]}</span>` : ""}</span><h3>${escapeHTML(item.title)}</h3><small>${formatDateTime(item.date)}</small></div>${safeNewsUrl(item.url) ? `<a href="${escapeHTML(item.url)}" target="_blank" rel="noopener noreferrer">Abrir ↗</a>` : ""}</article>`).join("") : `<div class="empty-state">${escapeHTML(data.warning || "Yahoo Finance no devolvió noticias para este activo.")}</div>`);
        } catch (error) { box.innerHTML = `<div class="empty-state">${escapeHTML(error.message || "No fue posible cargar las noticias.")}</div>`; }
    }

    function formatTechnicalValue(item, currency) {
        const value = item.value;
        if (value === null || value === undefined || value === "") return "N/D";
        if (item.key === "marketCap") return formatMoney(value, currency);
        if (item.key === "dividendYield") return `${(Number(value) * 100).toFixed(2)}%`;
        if (item.key === "dividendRate") return formatMoney(value, currency);
        if (item.key === "averageVolume") return formatNumber(value);
        return formatNumber(value);
    }

